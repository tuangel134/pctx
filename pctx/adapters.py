def _current_work(root: Path) -> tuple[str, list[str]]:
    from .tasks import load_tasks
    active = load_tasks(root).get("active")
    if active:
        return active["title"], active["next_actions"]
    handoff = load_handoff(root)
    if handoff:
        objective = str(handoff.get("objective", "")).strip()
        actions = [str(item) for item in handoff.get("next_actions", [])]
        return objective, actions
    records = load_records(root)
    actions = [record for record in records if record.get("type") == "next_action" and record.get("state") != "superseded"]
    if actions:
        return "", [str(record.get("statement", "")).splitlines()[0] for record in actions[:3]]
    return "", []


