def _merge_managed(existing: str, block: str) -> str:
    if START in existing and END in existing:
        before = existing.split(START, 1)[0].rstrip()
        after = existing.split(END, 1)[1].lstrip()
        return (before + "\n\n" if before else "") + block.rstrip() + ("\n\n" + after if after else "\n")
    if not existing.strip():
        return block
    return existing.rstrip() + "\n\n" + block


def sync_adapters(root: Path, names: list[str] | None = None, *, check: bool = False) -> dict[str, Any]:
    selected = names or list(TARGETS)
    unknown = [name for name in selected if name not in TARGETS]
    if unknown:
        raise ValueError(f"unknown adapter(s): {', '.join(unknown)}")
    results = []
    for name in selected:
        relative = TARGETS[name]
        target = safe_relative(root, relative)
        if name == "cline" and target.is_dir():
            relative += "/project-context.md"
            target = safe_relative(root, relative)
        existing = target.read_text(encoding="utf-8") if target.exists() else ""
        expected = _merge_managed(existing, render_bootstrap(root, relative))
        if name == "cursor" and not existing.lstrip().startswith("---"):
            expected = "---\ndescription: Portable PCTX project memory and task continuity\nalwaysApply: true\n---\n\n" + expected
        changed = existing != expected
        if changed and not check:
            write_text_atomic(target, expected)
        results.append({"adapter": name, "file": relative, "changed": changed, "written": changed and not check, "tokens": approximate_tokens(expected)})
    return {"check": check, "results": results, "drift": [item["file"] for item in results if item["changed"]]}
